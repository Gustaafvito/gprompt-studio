def set_idioma(lang: str) -> None:
    """Fija el idioma activo. 'en'/'english' → inglés; cualquier otro → español."""
    global _IDIOMA
    _IDIOMA = "en" if str(lang or "").strip().lower().startswith("en") else "es"


def get_idioma() -> str:
    """Devuelve el idioma activo ('es' o 'en')."""
    return _IDIOMA


def detectar_idioma_so() -> str:
    """Idioma por defecto en el PRIMER arranque (sin preferencia guardada):
    'en' si el SO está en inglés, 'es' en cualquier otro caso."""
    try:
        import locale
        loc = ""
        try:
            loc = (locale.getlocale()[0] or "") or (locale.getdefaultlocale()[0] or "")
        except Exception:
            loc = ""
        if not loc:
            import ctypes
            lang_id = ctypes.windll.kernel32.GetUserDefaultUILanguage()
            # 0x09 = inglés (LANG_ENGLISH)
            if (lang_id & 0xFF) == 0x09:
                return "en"
        if str(loc).lower().startswith(("en", "english")):
            return "en"
    except Exception:
        pass
    return "es"


def idioma_inicial(pref) -> str:
    """idioma guardado si existe; si no, detecta el del SO (primer arranque)."""
    return pref if pref in ("es", "en") else detectar_idioma_so()


def tr(texto_es: str) -> str:
    """Traduce `texto_es` al idioma activo. Fallback al español si no hay traducción."""
    if _IDIOMA == "en":
        return TRADUCCIONES.get(texto_es, texto_es)
    return texto_es


_INVERSA: dict[str, str] | None = None


def tr_es(texto: str) -> str:
    """Des-traduce un texto MOSTRADO a su clave ES original (identidad si no está).

    Para combos que muestran tr(clave) pero cuyo valor se usa como clave de un
    dict ES (estilos/fondos del avatar, tipo de LoRA, destinos...). Si dos claves
    ES comparten traducción, gana la última del diccionario (no ocurre en los
    combos que usan este helper).
    """
    global _INVERSA
    if _INVERSA is None:
        _INVERSA = {v: k for k, v in TRADUCCIONES.items()}
    return _INVERSA.get(texto, texto)
